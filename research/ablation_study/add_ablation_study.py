        "def bootstrap_ci(data, n_bootstrap=1000, ci=95):\n",
        "    \"\"\"Compute bootstrapped confidence interval.\"\"\"\n",
        "    data = np.array(data)\n",
        "    data = data[~np.isnan(data)]\n",
        "    if len(data) < 2:\n",
        "        mean = np.mean(data) if len(data) > 0 else 0\n",
