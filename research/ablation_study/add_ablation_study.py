def add_ablation_to_notebook():
    """Add ablation study cells to the notebook."""
    print("Adding ablation study to Week8_Comprehensive_Evaluation.ipynb")
    print("=" * 60)

    with open('Week8_Comprehensive_Evaluation.ipynb', 'r', encoding='utf-8') as f:
        nb = json.load(f)

    # Check if ablation already exists
    for cell in nb['cells']:
        source = ''.join(cell.get('source', []))
        if 'class AblationStudy' in source:
            print("Ablation study already exists in notebook")
            return

    # Find the right place to insert - after the main experiment results
    insert_idx = len(nb['cells']) - 2  # Before the last couple cells (usually export)

    # Look for a better insertion point (after comparison table)
    for i, cell in enumerate(nb['cells']):
        source = ''.join(cell.get('source', []))
        if 'df_comparison' in source and 'to_dict' in source:
            insert_idx = i + 1
            break

    # Insert all ablation cells
    for j, cell in enumerate(ABLATION_CELLS):
        # Fix source format for code cells
        if isinstance(cell.get('source'), list):
            cell['source'] = [line if line.endswith('\n') else line + '\n'
                             for line in cell['source']]
            # Remove trailing newline from last line
            if cell['source']:
                cell['source'][-1] = cell['source'][-1].rstrip('\n')

        nb['cells'].insert(insert_idx + j, cell)

    # Save
    with open('Week8_Comprehensive_Evaluation.ipynb', 'w', encoding='utf-8') as f:
        json.dump(nb, f, indent=1)

    print(f"Added {len(ABLATION_CELLS)} ablation study cells at index {insert_idx}")
    print("\nCells added:")
    print("  1. Ablation Study Introduction (markdown)")
    print("  2. AblationStudy class implementation")
    print("  3. Run ablation study")
    print("  4. Analyze results with bootstrap CIs")
    print("  5. Visualization")
    print("  6. Conclusions (markdown)")

